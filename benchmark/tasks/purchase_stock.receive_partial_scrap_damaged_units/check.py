"""Postcondition checks for purchase_stock.receive_partial_scrap_damaged_units.

Validates:
  1. Original receipt (origin=P-BENCH-DMG-001, NOT a backorder) is in
     state 'done' with a single Bench Parts move whose quantity == 15.
  2. Exactly one stock.scrap exists for Bench Parts linked to that
     picking, in state 'done', with scrap_qty == 5 and
     scrap_location_id.complete_name == 'WH/Lost'.
  3. A backorder stock.picking exists (backorder_id == original) with
     a Bench Parts move of product_uom_qty == 5, still not done
     (state in confirmed / assigned / waiting).
  4. The purchase.order is still state='purchase' (not cancelled).
"""

PO_ORIGIN = "P-BENCH-DMG-001"
VENDOR_NAME = "Bench Parts Vendor"
PRODUCT_NAME = "Bench Parts"
LOST_PATH = "WH/Lost"
DONE_QTY = 15.0
SCRAP_QTY = 5.0
BACKORDER_QTY = 5.0


def check(env):
    failures = []

    po = env["purchase.order"].search([("name", "=", PO_ORIGIN)], limit=1)
    if not po:
        return [f"Purchase order '{PO_ORIGIN}' not found"]
    if po.state not in ("purchase", "done"):
        failures.append(
            f"PO state is '{po.state}', expected 'purchase' or 'done' "
            f"(task must not cancel the PO)"
        )

    product = env["product.product"].search(
        [("name", "=", PRODUCT_NAME)], limit=1
    )
    if not product:
        return failures + [f"Product '{PRODUCT_NAME}' not found"]

    # ------------------------------------------------------------------
    # 1. Original receipt
    # ------------------------------------------------------------------
    originals = env["stock.picking"].search([
        ("origin", "=", PO_ORIGIN),
        ("picking_type_id.code", "=", "incoming"),
        ("backorder_id", "=", False),
    ])
    if not originals:
        return failures + [
            f"Original receipt (origin='{PO_ORIGIN}', no backorder_id) not "
            f"found — did not find the receipt auto-generated by the PO"
        ]
    if len(originals) > 1:
        failures.append(
            f"Expected exactly 1 original receipt for '{PO_ORIGIN}', "
            f"found {len(originals)}: {originals.mapped('name')}"
        )
    original = originals[:1]

    if original.state != "done":
        failures.append(
            f"Original receipt state is '{original.state}', expected 'done'"
        )

    # Bench Parts receipt move (exclude any scrap moves linked to this
    # picking — scraps auto-create a move on picking.move_ids too).
    moves = original.move_ids.filtered(
        lambda m: m.product_id.id == product.id and not m.scrap_id
    )
    if len(moves) != 1:
        failures.append(
            f"Original receipt has {len(moves)} Bench Parts receipt moves, "
            f"expected 1"
        )
    else:
        mv = moves[0]
        if abs((mv.quantity or 0.0) - DONE_QTY) > 1e-6:
            failures.append(
                f"Original receipt Bench Parts Done quantity is {mv.quantity}, "
                f"expected {DONE_QTY} — agent likely forgot to lower the Done "
                f"cell from 20 (demand) to 15 (received)"
            )
        # After validate-with-backorder, Odoo splits the move: the
        # original move's product_uom_qty is reduced to the Done amount
        # (15) and a new move with the remaining demand (5) is created
        # on the backorder picking. So we expect product_uom_qty == 15
        # on the original, NOT 20.
        if abs((mv.product_uom_qty or 0.0) - DONE_QTY) > 1e-6:
            failures.append(
                f"Original receipt Bench Parts demand is {mv.product_uom_qty}, "
                f"expected {DONE_QTY} (Odoo auto-splits demand on backorder)"
            )

    # ------------------------------------------------------------------
    # 2. Scrap record
    # ------------------------------------------------------------------
    scraps = env["stock.scrap"].search([
        ("product_id", "=", product.id),
        ("picking_id", "=", original.id),
    ])
    if not scraps:
        # Sometimes picking_id is NOT set if the agent re-opened the form;
        # fall back to a broader search.
        scraps = env["stock.scrap"].search([
            ("product_id", "=", product.id),
        ])
    if not scraps:
        failures.append(
            f"No stock.scrap record found for '{PRODUCT_NAME}' — agent did "
            f"not scrap the 5 damaged units"
        )
    elif len(scraps) > 1:
        failures.append(
            f"Expected exactly 1 stock.scrap for '{PRODUCT_NAME}', found "
            f"{len(scraps)}: {scraps.mapped('name')}"
        )
    else:
        s = scraps[0]
        if s.state != "done":
            failures.append(
                f"Scrap {s.name} state is '{s.state}', expected 'done' "
                f"(the scrap wizard must be validated)"
            )
        if abs((s.scrap_qty or 0.0) - SCRAP_QTY) > 1e-6:
            failures.append(
                f"Scrap quantity is {s.scrap_qty}, expected {SCRAP_QTY} — "
                f"agent likely left the default 1.00"
            )
        complete_name = (s.scrap_location_id.complete_name or "").strip()
        if complete_name != LOST_PATH:
            failures.append(
                f"Scrap location is '{complete_name}', expected '{LOST_PATH}' "
                f"— agent likely left the default Virtual Locations/Scrap"
            )

    # ------------------------------------------------------------------
    # 3. Backorder
    # ------------------------------------------------------------------
    backorders = env["stock.picking"].search([
        ("backorder_id", "=", original.id),
    ])
    if not backorders:
        failures.append(
            "No backorder receipt found — agent likely clicked 'No Backorder' "
            "instead of 'Create Backorder' in the validation dialog"
        )
    elif len(backorders) > 1:
        failures.append(
            f"Expected exactly 1 backorder, found {len(backorders)}: "
            f"{backorders.mapped('name')}"
        )
    else:
        bo = backorders[0]
        if bo.state == "done":
            failures.append(
                "Backorder receipt is already 'done' — agent validated it "
                "too (task only covers the first receipt + backorder)"
            )
        if bo.state == "cancel":
            failures.append("Backorder receipt is cancelled")
        bo_moves = bo.move_ids.filtered(
            lambda m: m.product_id.id == product.id and not m.scrap_id
        )
        if len(bo_moves) != 1:
            failures.append(
                f"Backorder has {len(bo_moves)} Bench Parts moves, expected 1"
            )
        elif abs((bo_moves[0].product_uom_qty or 0.0) - BACKORDER_QTY) > 1e-6:
            failures.append(
                f"Backorder Bench Parts Demand quantity is "
                f"{bo_moves[0].product_uom_qty}, expected {BACKORDER_QTY}"
            )

    return failures
